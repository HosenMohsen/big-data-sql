-- 1. UTILISATEURS & ADRESSES
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    token VARCHAR(255) NULL,
    phone_number VARCHAR(50) NULL,
    age INT NULL,
    status VARCHAR(10) DEFAULT 'A', -- 'A' = Actif, 'I' = Inactif, 'C' = Clôturé
    creation_date TIMESTAMPTZ DEFAULT NOW(),
    modification_date TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE adresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    domicile VARCHAR(255) NULL,
    travail VARCHAR(255) NULL,
    autre VARCHAR(255) NULL,
    pays VARCHAR(100) DEFAULT 'France',
    defaut VARCHAR(10) DEFAULT 'D' -- 'D' = Domicile, 'T' = Travail, 'A' = Autre
);

-- 2. CATALOGUE : MARQUES, PRODUITS, CATÉGORIES & VARIANTES
CREATE TABLE marques (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description TEXT NULL
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    description TEXT NULL,
    sous_categories VARCHAR(255) NULL
);

CREATE TABLE produits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    description TEXT NULL,
    reference_commerciale VARCHAR(100) NOT NULL UNIQUE,
    marque_id BIGINT NULL REFERENCES marques(id) ON DELETE SET NULL,
    creation_date TIMESTAMPTZ DEFAULT NOW(),
    modification_date TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE produit_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id BIGINT NOT NULL REFERENCES produits(id) ON DELETE CASCADE,
    categorie_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    UNIQUE (produit_id, categorie_id)
);

CREATE TABLE variantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES produits(id) ON DELETE CASCADE,
    taille VARCHAR(50) NULL,
    couleur VARCHAR(50) NULL,
    sku VARCHAR(100) NOT NULL UNIQUE,
    stock INT NOT NULL DEFAULT 0,
    modification_date TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE variantes_prix (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variante_id BIGINT NOT NULL REFERENCES variantes(id) ON DELETE CASCADE,
    price NUMERIC(10, 2) NOT NULL,
    device VARCHAR(10) DEFAULT 'EUR',
    date_debut DATE NULL,
    date_fin DATE NULL,
    creation_date TIMESTAMPTZ DEFAULT NOW()
);

-- 3. PANIER & ITEMS DE PANIER
CREATE TABLE panier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NULL REFERENCES users(id) ON DELETE CASCADE,
    session_token VARCHAR(255) NULL,
    variant_sku VARCHAR(100) NULL,
    quantite INT NULL,
    creation_date TIMESTAMPTZ DEFAULT NOW(),
    modification_date TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE panier_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    panier_id BIGINT NOT NULL REFERENCES panier(id) ON DELETE CASCADE,
    variante_id BIGINT NOT NULL REFERENCES variantes(id) ON DELETE CASCADE,
    quantite INT NOT NULL DEFAULT 1,
    date_modification TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (panier_id, variante_id)
);

-- 4. PROMOTIONS & CODES PROMO
CREATE TABLE promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    pourcentage NUMERIC(5, 2) NOT NULL,
    type VARCHAR(50) NOT NULL, -- 'produit', 'categorie', 'commande'
    produit_id BIGINT NULL REFERENCES produits(id) ON DELETE CASCADE,
    categorie_id BIGINT NULL REFERENCES categories(id) ON DELETE CASCADE,
    start_date TIMESTAMPTZ NULL,
    end_date TIMESTAMPTZ NULL
);

CREATE TABLE code_promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    promotions_id BIGINT NOT NULL REFERENCES promotions(id) ON DELETE CASCADE,
    nombre_usage INT DEFAULT 0,
    user_id BIGINT NULL REFERENCES users(id) ON DELETE SET NULL
);

-- 5. COMMANDES
CREATE TABLE commandes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_commande VARCHAR(100) NOT NULL UNIQUE,
    panier_id BIGINT NULL REFERENCES panier(id) ON DELETE SET NULL,
    user_id BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    etat VARCHAR(50) DEFAULT 'en_attente',
    email VARCHAR(255) NULL,
    adresse TEXT NULL,
    ville VARCHAR(100) NULL,   -- ville de livraison
    pays VARCHAR(100) NULL,    -- pays de livraison
    numero_tel VARCHAR(50) NULL,
    creation_date TIMESTAMPTZ DEFAULT NOW()
);

